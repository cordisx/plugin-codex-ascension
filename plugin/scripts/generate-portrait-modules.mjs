import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../src/assets/portraits/', import.meta.url))
const stages = ['plastic', 'bronze', 'steel', 'silver', 'gold']
const declarations = await Promise.all(stages.map(async stage => {
  const data = await readFile(`${root}tibo-${stage}.png`, 'base64')
  return `export const ${stage}Portrait: string = '${data}'`
}))

await writeFile(`${root}generated.ts`, `// Generated by scripts/generate-portrait-modules.mjs.\n${declarations.join('\n')}\n`)

const identityRoot = fileURLToPath(new URL('../src/assets/identity/', import.meta.url))
const iconData = await readFile(fileURLToPath(new URL('../../public/apple-touch-icon.png', import.meta.url)), 'base64')
await mkdir(identityRoot, { recursive: true })
await writeFile(`${identityRoot}generated.ts`, `// Generated from the approved site icon by scripts/generate-portrait-modules.mjs.\nexport const ascensionIcon: string = '${iconData}'\n`)
